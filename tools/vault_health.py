def all_docs() -> list[Path]:
    """Every living markdown doc (excludes archive/obsidian/git and this tool's
    own generated outputs)."""
    docs = []
    for path in sorted(ROOT.rglob("*.md")):
        rel = path.relative_to(ROOT)
        if any(part in SKIP_PARTS for part in rel.parts):
            continue
        if rel.as_posix() in GENERATED_OUTPUTS:
            continue
        docs.append(path)
    return docs


def _first_heading(path: Path) -> str | None:
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return None


_SENTENCE_END = re.compile(r"(?<=[.!?])\s")

# Section headings that introduce a document's own summary, best first. Contracts
# use `## Purpose`; golden examples use `## Demonstrates` (a bullet list).
_SUMMARY_SECTIONS = ("purpose", "demonstrates", "purpose & precedent", "what it is")


def _blocks(lines: list[str]) -> list[tuple[str, str]]:
    """(section, text) for each paragraph/bullet, with hard-wrapped lines joined.

    Markdown in this vault is hard-wrapped at ~90 columns, so a single source
    line is usually half a sentence. Reading one line at a time is what produced
    drawer descriptions like "rows." and "…access to underlying".
    """
    out: list[tuple[str, str]] = []
    section, buf, in_fm, fences = "", [], False, 0

    def flush() -> None:
        if buf:
            out.append((section, " ".join(buf).strip()))
            buf.clear()

    for i, raw in enumerate(lines):
        line = raw.rstrip()
        stripped = line.strip()
        if i == 0 and stripped == "---":
            in_fm = True
            continue
        if in_fm:
            in_fm = stripped != "---"
            continue
        if stripped.startswith("```"):
            fences += 1
            flush()
            continue
        if fences % 2:
            continue
        if stripped.startswith("#"):
            flush()
            if stripped.startswith("## "):
                section = stripped[3:].strip().lower()
            continue
        if not stripped or stripped.startswith(("|", ">", "<!--", "---")):
            flush()
            continue
        if stripped.startswith(("- ", "* ", "+ ")) or re.match(r"^\d+\.\s", stripped):
            flush()
            buf.append(re.sub(r"^([-*+]\s|\d+\.\s)", "", stripped))
            continue
        buf.append(stripped)
    flush()
    return out


def _looks_like_prose(s: str) -> bool:
    """True only for something a reader would accept as a written sentence.

    Golden examples embed screenshot links and repo paths; letting those through
    put strings like `foo.png(screenshots/connected-platform/foo.png)` in front of
    readers on a page whose whole subject is documentation quality. When nothing
    qualifies, `_doc_summary` returns "" and the drawer shows the name alone —
    no description is strictly better than a broken one.
    """
    if len(s) < 30 or "](" in s or "|" in s:
        return False
    if re.search(r"\.(png|jpe?g|svg|md|tsx?|css|json|py|html|canvas|base)\b", s):
        return False
    if s.count("/") >= 2:  # a repo path; single slashes ("semantic/status") are fine
        return False
    return s[:1].isupper() and s.rstrip().endswith((".", "!", "?"))


def _doc_summary(path: Path, fm: dict | None) -> str:
    """One plain sentence describing a document, for the private drawer lists.

    A drawer that lists 12 slugs and nothing else tells a reader what exists but
    not what any of it is. Preference order, most-authored first: frontmatter
    `description` (agents and skills carry one) -> the first qualifying block
    under a summary heading -> the first qualifying block anywhere.

    Private pages only — a description can name a product surface, and the
    page is encrypted at publish time rather than stripped.
    """
    def sentence(s: str) -> str:
        """Markup stripped, first sentence only — full length, so the prose test
        sees a real sentence. Shortening happens after it passes, never before:
        an ellipsis ending would fail `_looks_like_prose` on its own output."""
        s = re.sub(r"[`*_]", "", str(s)).strip()
        s = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", s)  # [text](url) -> text
        return _SENTENCE_END.split(s, 1)[0].strip()

    def shorten(s: str) -> str:
        # Generous: these wrap freely in the drawer, and a sentence cut mid-clause
        # with no way to expand is worse than a long one.
        return s if len(s) <= 220 else s[:217].rsplit(" ", 1)[0] + "…"

    described = (fm or {}).get("description")
    if described:
        return shorten(sentence(described))

    blocks = _blocks(path.read_text(encoding="utf-8", errors="ignore").splitlines())
    ordered = [(s, t) for w in _SUMMARY_SECTIONS for s, t in blocks if s == w] + blocks
    for _, text in ordered:
        candidate = sentence(text)
        if _looks_like_prose(candidate):
            return shorten(candidate)
    return ""


def block_readiness(inventory: dict[str, list[dict]]) -> dict:
    """Review state across the six cards only — the reusable pieces.

    The vault-wide share is carried by documents nobody builds from (benchmark
    records, reviews, indexes). Blind review, 2026-07-30: the page reported 28%
    approved while the material a designer is told to follow was 7% approved, and
    that gap was derivable but stated nowhere. It is stated now.
    """
    counts = {"stable": 0, "in-review": 0, "draft": 0, None: 0}
    for rows in inventory.values():
        for it in rows:
            counts[it.get("status")] = counts.get(it.get("status"), 0) + 1
    with_status = sum(v for k, v in counts.items() if k)
    return {"with_status": with_status, "approved": counts["stable"],
            "pct": round(100 * counts["stable"] / with_status) if with_status else 0}


def summary_gap(inventory: dict[str, list[dict]]) -> list[str]:
    """Items with no hand-written `SUMMARIES` entry, as "Area / name".

    The drift signal for a hand-maintained map. Add a 13th component contract and
    it appears here immediately, rather than quietly rendering its own opening
    sentence — which is accurate but written for someone who already knows the
    system, and is exactly what this dict exists to replace.
    """
    return sorted(f"{area} / {it['name']}"
                  for area, rows in inventory.items()
                  for it in rows if not it.get("written"))


def _summary_key(path: Path) -> str:
    """Stable `SUMMARIES` key for a document.

    Filename stem for everything except skills, which live at
    `skills/<slug>/SKILL.md` — there the slug is the parent directory. Keyed off
    the path rather than the displayed name because examples show a title
    ("Button In All States") that is not their filename.
    """
    return path.parent.name if path.name == "SKILL.md" else path.stem


def _example_name(path: Path) -> str:
    heading = _first_heading(path) or path.stem
    for prefix in ("Golden Example: ", "Golden Example — "):
        if heading.startswith(prefix):
            return heading[len(prefix):]
    return heading


def build_inventory(docs: list[Path]) -> dict[str, list[dict]]:
    """area -> [{name, status, desc, path, written}] sorted, for the drill-down.

    `desc` prefers the hand-written `SUMMARIES` entry and falls back to
    `_doc_summary()`; `written` records which, so `summary_gap()` can report how
    many items are still on the fallback. `path` is the repo-relative location,
    derived from the scanned file so it cannot go stale.
    """
    traps = agent_traps()
    by_type: dict[str, list[Path]] = {}
    for path in docs:
        fm = lf.parse_frontmatter(path)
        if fm and fm.get("type"):
            by_type.setdefault(fm["type"], []).append(path)

    def entry(p: Path, name: str, fm: dict, status) -> dict:
        written = SUMMARIES.get(_summary_key(p))
        return {"name": name, "status": status,
                "desc": written or _doc_summary(p, fm),
                "written": bool(written),
                "path": p.relative_to(ROOT).as_posix()}

    def items(paths: list[Path], namer) -> list[dict]:
        out = []
        for p in paths:
            fm = lf.parse_frontmatter(p) or {}
            out.append(entry(p, namer(p), fm, fm.get("status")))
        return sorted(out, key=lambda d: d["name"].lower())

    agents = sorted((ROOT / "design-brain" / "agents").glob("*.md"))
    skills = sorted((ROOT / "design-brain" / "skills").glob("*/SKILL.md"))
    inv: dict[str, list[dict]] = {
        # Agent rows carry their trap/evidence counts too, so the drawer can show
        # which agents have accumulated failure knowledge and which haven't.
        "Agents": [{**it, "traps": traps.get(it["name"])}
                   for it in items(agents, lambda p: p.stem)],
        "Skills": [
            entry(p, (fm := lf.parse_frontmatter(p) or {}).get("name", p.parent.name),
                  fm, None)
            for p in skills
        ],
        "Component contracts": items(by_type.get("component-contract", []), lambda p: p.stem),
        "Pattern contracts": items(by_type.get("pattern-contract", []), lambda p: p.stem),
        "Examples": items(by_type.get("example", []), _example_name),
        "Platform profiles": items(by_type.get("platform-profile", []), lambda p: p.stem),
    }
    inv["Skills"].sort(key=lambda d: d["name"].lower())
    return inv


